"""Safe read-only green annotations for values that compare equal.

Only verified, nonempty matched values become green overlays. Unknown/unreadable
fields and approximate text matches must not be promoted to successful checks.
No corrective finding is generated by this module.
"""
from __future__ import annotations

import difflib
import pymupdf as fitz

from correction_markers import marker_rect, marker_label, scan_ink_guard


def match_marks(records, *, side):
    """Convert independently verified Waybill match records to word boxes."""
    key = 'ref_hits' if side == 'ref' else 'exam_hits'
    result = []
    seen = set()
    for record in records:
        field = record['field']
        for hit in record.get(key, ()):
            rect = fitz.Rect(hit['rect'])
            page = hit['page']
            if rect.is_empty or rect.is_infinite or not 0 <= int(page):
                continue
            identity = (field, page, tuple(round(x, 2) for x in rect))
            if identity in seen:
                continue
            seen.add(identity)
            result.append({'field': field, 'page': int(page), 'rect': rect, 'kind': 'Sama'})
    return result


def _locate_unique_phrase(pdf, text):
    """Only trust text whose complete phrase is on one PDF page at one place."""
    tokens = ' '.join(str(text).split())
    if len(tokens) < 12:
        return []
    candidates = []
    for page_id, page in enumerate(pdf):
        hits = page.search_for(tokens)
        if hits:
            candidates.append((page_id, hits))
    if len(candidates) != 1:
        return []
    page_id, hits = candidates[0]
    # Do not highlight a phrase repeated multiple times in a PDF.
    if len(hits) != 1:
        return []
    return [{'page': page_id, 'rect': fitz.Rect(r), 'kind': 'Sama'} for r in hits]


def compare_equal_paragraphs(reference_pdf, examined_pdf, ref_blocks, exam_blocks, selected_indices):
    """Strictly equal aligned paragraphs only; no fuzzy/semantic guesses.

    The general-purpose paragraph engine has no field-level PDF provenance, so
    uncertain text position is intentionally omitted instead of painted green.
    """
    a = [' '.join(str(t).split()) for t in ref_blocks]
    b = [' '.join(str(t).split()) for t in exam_blocks]
    selected = set(selected_indices)
    matched = []
    align = difflib.SequenceMatcher(None, a, b, autojunk=False)
    with fitz.open(reference_pdf) as ref, fitz.open(examined_pdf) as exam:
        for operation, i0, i1, j0, j1 in align.get_opcodes():
            if operation != 'equal':
                continue
            for aidx, bidx in zip(range(i0, i1), range(j0, j1)):
                if aidx not in selected or len(a[aidx]) < 12 or not a[aidx]:
                    continue
                a_hits = _locate_unique_phrase(ref, a[aidx])
                b_hits = _locate_unique_phrase(exam, b[bidx])
                if not a_hits or not b_hits:
                    continue
                matched.append({'field': f'Paragraf {aidx + 1}',
                                'reference_text': a[aidx], 'examined_text': b[bidx],
                                'ref_hits': a_hits, 'exam_hits': b_hits})
    return matched


def number_match_marks(marks, visible_records):
    """Assign deterministic #01..#NN labels based on the *visible* matched fields.

    A field gets one ID on both PDF sides, including when it has many token
    rectangles. Original source mark records remain untouched for session/audit.
    """
    field_numbers = {rec['field']: number for number, rec in
                     enumerate(visible_records, start=1)}
    return [{**mark, 'id': field_numbers[mark['field']]}
            for mark in marks if mark.get('field') in field_numbers]


def layout_match_markers(page, page_marks):
    """Find safe, compact numbered badges next to verified green highlights.

    Returns a single green badge for each matched field per source page. Badges
    never cover known text or other highlights; with no safe area the highlight
    and the numbered row in the inspector still remain visible.
    """
    unique = {}
    protected = []
    for mark in page_marks:
        rect = fitz.Rect(mark['rect'])
        if rect.is_empty or rect.is_infinite:
            continue
        protected.append(rect)
        number = mark.get('id')
        if not isinstance(number, int) or number < 1:
            continue
        unique.setdefault(number, {'id': number, 'field': mark['field'], 'anchors': []})['anchors'].append(rect)
    if not unique:
        return []
    word_boxes = [fitz.Rect(word[:4]) for word in page.get_text('words')]
    # Image-backed headers can contain text absent from get_text('words').
    # The raster guard also protects those letters and printed table lines.
    ink_guard = scan_ink_guard(page)
    placed = []
    badges = []
    for number, item in sorted(unique.items()):
        box = None
        # For densely packed cargo/addresses, the first word may offer no safe
        # badge location. Try neighboring highlighted words of the same field
        # rather than omitting its number or overlaying another column's text.
        anchors = item['anchors']
        for anchor in anchors[:16]:
            box = marker_rect(anchor, marker_label([number]),
                              page.rect.width, page.rect.height,
                              text_boxes=word_boxes, occupied=placed,
                              protected=protected, ink_guard=ink_guard)
            if box is not None:
                break
        if box is None:
            continue
        badges.append({'id': number, 'field': item['field'], 'rect': box})
        placed.append(box)
    return badges
